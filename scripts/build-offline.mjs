/** Post-build: fingerprint and precache only this site's own static files. */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
const root = path.resolve('dist');
async function walk(dir) {
  const result = [];
  for (const file of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, file.name);
    if (file.isDirectory()) result.push(...await walk(p));
    else if (file.name !== 'sw.js') result.push(path.relative(root, p).split(path.sep).join('/'));
  }
  return result.sort();
}
const files = (await walk(root)).filter(file => !['live/research.json', 'live/questions.json'].includes(file));
const hash = createHash('sha256');
for (const file of files) { hash.update(file); hash.update(await readFile(path.join(root, file))); }
const revision = hash.digest('hex').slice(0, 16);
const sw = `/* Generated by scripts/build-offline.mjs. Do not edit dist files. */
const SCOPE = self.registration.scope;
const PREFIX = 'ssc-cgl:' + new URL(SCOPE).pathname + ':';
const CACHE = PREFIX + '${revision}';
const FILES = ${JSON.stringify(files)}.map(p => new URL(p, SCOPE).href);
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES.map(url => new Request(url, {cache: 'reload'})))));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith(PREFIX) && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('message', event => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting();
});
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin || !url.href.startsWith(SCOPE)) return;
  // Never answer an explicit live-update check from an offline snapshot.
  if (['live/research.json', 'live/questions.json'].some(p => url.pathname === new URL(p, SCOPE).pathname)) {
    event.respondWith(fetch(event.request, {cache: 'no-store'}));
    return;
  }
  if (event.request.mode === 'navigate') {
    event.respondWith(fetch(event.request).catch(() => caches.open(CACHE).then(async cache => (await cache.match(event.request, {ignoreSearch: true})) || cache.match(new URL('index.html', SCOPE).href))));
  } else if (FILES.includes(url.href)) {
    event.respondWith(caches.open(CACHE).then(async cache => (await cache.match(event.request)) || fetch(event.request)));
  }
});
`;
await writeFile(path.join(root, 'sw.js'), sw);
console.log(`Offline cache: ${files.length} files, revision ${revision}`);
